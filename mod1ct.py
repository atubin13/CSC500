# Using the latest version of Python, write a single program that performs
# basic arithmetic. Your program must prompt the user to input two numbers
# ($num1$ and $num2$) and then calculate and display the results for:
# Addition ($num1 + num2$)
# Subtraction ($num1 - num2$)
# Multiplication ($num1 \times num2$)
# Division ($num1 / num2$)#

num1 = float(input("Please type in a number: "))
num2 = float(input("Please type in another number: "))
print("Addition: ", num1 + num2)
print("Subtraction: ", num1 - num2)
print("Multiplication: ", num1 * num2)
print("Division: ", num1 / num2)
